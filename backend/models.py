"""Database models for AeroRehab.

Tables:
- astronauts: user profiles
- sessions: exercise sessions with extracted features
- reports: KIS scores, bands, deviations, recommendations
"""
from datetime import datetime
from sqlalchemy import Column, Integer, String, Float, DateTime, ForeignKey, Text
from sqlalchemy.orm import relationship

from .database import Base


class Astronaut(Base):
    """Astronaut profile.

    One astronaut can have many sessions.
    """
    __tablename__ = "astronauts"

    id = Column(String, primary_key=True, index=True)  # e.g. "a1", "demo"
    name = Column(String, nullable=True)  # Full name (optional for now)
    mission = Column(String, nullable=True)  # e.g. "ISS Expedition 70"
    baseline_n = Column(Integer, default=5)  # Number of sessions needed for baseline
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship: one astronaut has many sessions
    sessions = relationship("Session", back_populates="astronaut", cascade="all, delete-orphan")


class Session(Base):
    """Exercise session with extracted features.

    Each session belongs to one astronaut and has one report.
    """
    __tablename__ = "sessions"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    astronaut_id = Column(String, ForeignKey("astronauts.id"), nullable=False)
    session_number = Column(Integer, nullable=False)  # 0, 1, 2, ... for this astronaut

    # Extracted features (from features.py)
    rom_deg = Column(Float, nullable=False)
    peak_flexion_deg = Column(Float, nullable=False)
    smoothness = Column(Float, nullable=False)
    asymmetry = Column(Float, nullable=False)
    rep_consistency = Column(Float, nullable=False)
    tempo_s = Column(Float, default=4.0)
    mean_load = Column(Float, default=400.0)

    # Pain rating
    pain_0_10 = Column(Integer, default=0)

    # Timestamp
    timestamp = Column(DateTime, default=datetime.utcnow)

    # Relationships
    astronaut = relationship("Astronaut", back_populates="sessions")
    report = relationship("Report", back_populates="session", uselist=False, cascade="all, delete-orphan")


class Report(Base):
    """KIS report for one session.

    Generated by AeroRehabMonitor after ingesting a session.
    """
    __tablename__ = "reports"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    session_id = Column(Integer, ForeignKey("sessions.id"), nullable=False, unique=True)

    # Baseline status
    baseline_ready = Column(Integer, default=0)  # 0 = False, 1 = True (SQLite doesn't have native boolean)

    # KIS and band (null until baseline is ready)
    kis = Column(Float, nullable=True)
    band = Column(String, nullable=True)  # "GREEN", "YELLOW", "RED"

    # Sub-scores (JSON stored as text)
    subscores_json = Column(Text, nullable=True)  # {"rom_deg": 100.0, "smoothness": 85.3, ...}

    # Worse-Z values (JSON stored as text)
    worse_z_json = Column(Text, nullable=True)  # {"rom_deg": 0.2, "smoothness": 1.5, ...}

    # Deviations (JSON array stored as text)
    deviations_json = Column(Text, nullable=True)  # [{"session_id": 6, "feature": "rom_deg", ...}, ...]

    # Recommendations (JSON array stored as text)
    recommendations_json = Column(Text, nullable=True)  # [{"level": "INFO", "message": "..."}, ...]

    # Timestamp
    timestamp = Column(DateTime, default=datetime.utcnow)

    # Relationship
    session = relationship("Session", back_populates="report")
